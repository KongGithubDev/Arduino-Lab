"""Build simulator/js/catalog.js from the READMEs (names, wiring, example code).

    python tools/build_simulator_data.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "blender"))
from wiring_spec import parse  # noqa: E402

items = []
for base in ("sensors", "modules"):
    for p in sorted((ROOT / base).glob("*/README.md")):
        spec = parse(p)
        text = p.read_text(encoding="utf-8")
        blocks = re.findall(r"^## (โค้ด[^\n]*)\n(.*?)(?=^## )", text, re.S | re.M)
        examples = []
        for title, body in blocks:
            for code in re.findall(r"```(?:cpp|c|arduino)\n(.*?)```", body, re.S):
                examples.append({"title": title.strip(), "code": code.rstrip() + "\n"})
        desc = re.search(r"^## รายละเอียด\n+(.+?)\n", text, re.M)
        img = re.search(r"\(\.\./\.\./(assets/images/[^)]+)\)", text)
        items.append({
            "key": spec["key"], "code": spec["code"], "name": spec["name"],
            "category": "sensor" if base == "sensors" else "module",
            "desc": desc.group(1).strip() if desc else "",
            "image": img.group(1) if img else None,
            "readme": f"{base}/{spec['key']}/README.md",
            "wires": spec["wires"], "examples": examples,
        })
items.sort(key=lambda x: x["code"])
out = ROOT / "simulator" / "js" / "catalog.js"
out.write_text("// generated by tools/build_simulator_data.py - do not edit\nexport const CATALOG = " + json.dumps(items, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(len(items), "items,", sum(len(i["examples"]) for i in items), "examples ->", out)
